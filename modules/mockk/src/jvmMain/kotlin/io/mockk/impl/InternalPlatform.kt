actual object InternalPlatform {
    actual fun time(): Long = System.nanoTime()

    actual fun ref(obj: Any): Ref = CommonRef(obj)

    actual fun hkd(obj: Any): String = Integer.toHexString(InternalPlatformDsl.identityHashCode(obj))

    actual fun isPassedByValue(cls: KClass<*>): Boolean =
        when (cls) {
            java.lang.Boolean::class -> true
            java.lang.Byte::class -> true
            java.lang.Short::class -> true
            java.lang.Character::class -> true
            java.lang.Integer::class -> true
            java.lang.Long::class -> true
            java.lang.Float::class -> true
            java.lang.Double::class -> true
            java.lang.String::class -> true
            else -> false
        }

    actual fun <K, V> MutableMap<K, V>.customComputeIfAbsent(
        key: K,
        valueFunc: (K) -> V,
    ): V {
        val value = get(key)
        return if (value == null) {
            val newValue = valueFunc(key)
            put(key, newValue)
            newValue
        } else {
            value
        }
    }

    actual fun <K, V> weakMap(): WeakMap<K, V> = JvmWeakConcurrentMap()

    actual fun <K, V> identityMap(): MutableMap<K, V> = CommonIdentityHashMapOf()

    actual fun <T> synchronizedMutableList(): MutableList<T> = synchronizedList(mutableListOf<T>())

    actual fun <K, V> synchronizedMutableMap(): MutableMap<K, V> = synchronizedMap(hashMapOf())

    // UnsupportedOperationException is thrown for some internal classes generated by the Kotlin compiler
    private fun isValueClass(clazz: KClass<*>) =
        try {
            clazz.isValue
        } catch (_: UnsupportedOperationException) {
            false
        }

    actual fun packRef(arg: Any?): Any? =
        when {
            arg == null -> null
            isValueClass(arg::class) -> packRef(arg.boxedValue) ?: ref(arg)
            isPassedByValue(arg::class.boxedClass) -> arg.boxedValue
            else -> ref(arg)
        }

    actual fun prettifyRecordingException(ex: Throwable): Throwable =
        when {
            ex is ClassCastException ->
                MockKException(
                    when (ex.message) {
                        null ->
                            "Class cast exception happened.\n" +
                                "WARN: 'message' property in ClassCastException provided by JVM is null, " +
                                "auto-hinting is not possible. \n" +
                                "This is most probably happening due to Java optimization enabled. \n" +
                                "You can use `hint` before call or use -XX:-OmitStackTraceInFastThrow to disable " +
                                "this optimization behaviour and make auto-hinting work. \n" +
                                "For example in gradle use: \n" +
                                "\n" +
                                "test {\n" +
                                "   jvmArgs '-XX:-OmitStackTraceInFastThrow'\n" +
                                "}"
                        else ->
                            "Class cast exception happened.\n" +
                                "Probably type information was erased.\n" +
                                "In this case use `hint` before call to specify " +
                                "exact return type of a method.\n"
                    },
                    ex,
                )

            ex is NoClassDefFoundError &&
                ex.message?.contains("kotlinx/coroutines/") ?: false ->
                MockKException(
                    "Add coroutines support artifact 'org.jetbrains.kotlinx:kotlinx-coroutines-core' to your project ",
                    ex,
                )

            else -> ex
        }

    actual fun <T : Any> copyFields(
        to: T,
        from: T,
    ) {
        if (to is MockKProxyDelegate) {
            // The proxy stands in for an instance of a hidden class - e.g. a Kotlin 2 lambda
            // compiled with invokedynamic (#1313). Hidden classes can be neither subclassed nor
            // instrumented, so the proxy was built over the hidden class's interfaces and keeps
            // the original instance to forward un-stubbed "call original" requests to. Its
            // captured fields live in the original and cannot be copied onto the differently
            // shaped proxy, so delegating is all the spy state transfer there is.
            to.mockkSetOriginal(from)
            return
        }

        fun copy(
            to: Any,
            from: Any,
            cls: Class<*>,
        ) {
            for (field in cls.declaredFields) {
                if (Modifier.isStatic(field.modifiers)) {
                    continue
                }
                if (isRunningAndroidInstrumentationTest() && field.name.startsWith("shadow$")) {
                    continue
                }
                InternalPlatformDsl.makeAccessible(field)
                val value = field.get(from)
                field.set(to, value)
            }
            if (cls.superclass != null) {
                copy(to, from, cls.superclass)
            }
        }
        copy(to, from, from::class.java)
        rebindLazyDelegates(to)
    }

    // A Kotlin `by lazy` delegate field is named "<property>$delegate" and holds a Lazy whose
    // initializer lambda captures the object the property belongs to. Copying such a delegate
    // verbatim leaves the spy with a delegate still bound to the original object: evaluating the
    // property later runs the initializer against the original's getters, which are not
    // intercepted by the spy. A spy instantiated through the default constructor instead gets a
    // delegate whose initializer captures the spy itself, so mocked properties are resolved
    // through the spy (see #1262). Rebinding recreates the delegate with the initializer
    // capturing the spy, aligning the two paths. Whatever cannot be rebound safely keeps the
    // verbatim copy: a computed delegate has dropped its initializer along with its value, and
    // Lazy implementations outside the standard library are left to their owners.
    private fun <T : Any> rebindLazyDelegates(to: T) {
        var cls: Class<*>? = to::class.java
        while (cls != null) {
            for (field in cls.declaredFields) {
                if (Modifier.isStatic(field.modifiers)) {
                    continue
                }
                if (!field.name.endsWith("\$delegate")) {
                    continue
                }
                try {
                    InternalPlatformDsl.makeAccessible(field)
                    val copiedDelegate = field.get(to)
                    if (copiedDelegate is Lazy<*>) {
                        rebindLazyDelegate(to, copiedDelegate)?.let { field.set(to, it) }
                    }
                } catch (_: Throwable) {
                    // keep the verbatim copied delegate
                }
            }
            cls = cls.superclass
        }
    }

    private fun <T : Any> rebindLazyDelegate(
        to: T,
        copiedDelegate: Lazy<*>,
    ): Lazy<*>? {
        val implClass = copiedDelegate::class.java
        val mode =
            when (implClass.name) {
                "kotlin.SynchronizedLazyImpl" -> LazyThreadSafetyMode.SYNCHRONIZED
                "kotlin.SafePublicationLazyImpl" -> LazyThreadSafetyMode.PUBLICATION
                "kotlin.UnsafeLazyImpl" -> LazyThreadSafetyMode.NONE
                else -> return null
            }

        val initializerField = implClass.getDeclaredField("initializer")
        InternalPlatformDsl.makeAccessible(initializerField)
        // A computed delegate keeps its value but has dropped the initializer: nothing to rebind.
        val initializer = initializerField.get(copiedDelegate) ?: return null

        val initializerClass = initializer::class.java
        val receiverConstructor =
            initializerClass.declaredConstructors.firstOrNull { constructor ->
                constructor.parameterCount == 1 &&
                    constructor.parameterTypes[0].isAssignableFrom(to::class.java)
            } ?: return null

        InternalPlatformDsl.makeAccessible(receiverConstructor)

        @Suppress("UNCHECKED_CAST")
        val reboundInitializer = receiverConstructor.newInstance(to) as () -> Any?
        return lazy(mode) { reboundInitializer() }
    }

    actual fun captureStackTrace(): () -> List<StackElement> {
        val ex = Exception("Stack trace")
        return {
            val stack = ex.stackTrace ?: arrayOf<StackTraceElement>()
            stack.map {
                StackElement(
                    it.className ?: "-",
                    it.fileName ?: "-",
                    it.methodName ?: "-",
                    it.lineNumber,
                    it.isNativeMethod,
                )
            }
        }
    }

    actual fun weakRef(value: Any): WeakRef {
        val weakRef = WeakReference(value)
        return object : WeakRef {
            override val value: Any?
                get() = weakRef.get()
        }
    }

    actual fun multiNotifier(): MultiNotifier = JvmMultiNotifier()

    actual inline fun <T> synchronized(
        obj: Any,
        block: () -> T,
    ) = kotlin.synchronized(obj, block)

    inline fun <reified T : Any> loadPlugin(
        className: String,
        msg: String = "",
    ) = try {
        T::class.cast(Class.forName(className).getDeclaredConstructor().newInstance())
    } catch (ex: Exception) {
        throw MockKException("Failed to load plugin. $className $msg", ex)
    }

    fun isRunningAndroidInstrumentationTest(): Boolean =
        System
            .getProperty("java.vendor", "")
            .lowercase(Locale.US)
            .contains("android")

    actual fun getMockKeys(mocks: List<Any>): List<Any> =
        mocks.map {
            when (it) {
                is KClass<*> -> it.java
                is KProperty<*> -> it.getter.declaringKotlinFile.java
                is KFunction<*> -> it.declaringKotlinFile.java
                else -> it
            }
        }
}
